"""`scribe-eval ingest-corpus`: index the eval corpus into an 'eval' workspace with the same
indexer the service uses (T12). Never falls back to environment database URLs.

Corpus-agnostic (A4a):

* ``--dataset <dir>`` (default benchmarks/datasets/golden-v1) names the dataset whose eval workspace is filled and
  ``--corpus <dir>`` (default fixtures/corpus) is the directory of documents.
* WORKSPACE SCHEME: every dataset has its own eval workspace, found/created by ``owner_user_id`` =
  ``eval_owner(dataset)`` = ``"eval-" + <dataset directory name>``, e.g. ``eval-golden-v1`` (the pre-A4a constant, so
  existing ingested databases keep working) and ``eval-gov-v1``. The workspace UUID is generated by the database, kind
  ``'eval'``. ``run-profile`` finds the workspace by the same owner id.
* ``--manifest <manifest.json>`` (benchmarks/corpora/<name>/manifest.json): ``documents[]`` entries have an ``id`` and an
  ``ingest_file``. NAME MAPPING: cases reference the ORIGINAL file name ``<id>.pdf``; the file registered in the workspace
  is named ``<id>.pdf`` too (so ``doc`` fields in cases keep matching), but its BYTES are read from
  ``<corpus>/<ingest_file>`` (the original, or the derived ``<id>.raster.pdf`` image-only copy). A missing ingest_file
  refuses the whole run. Without ``--manifest`` every supported file in the corpus directory is ingested under its own name.
* Spend: with the real (gemini) embedder a pre-run estimate (embedding tokens + an OCR allowance, see
  ``estimate_ingest_usd``) is checked against the spend cap (scribe_eval.cost) before any provider call; the actual spend
  is appended to the ledger afterwards.
"""
from __future__ import annotations

import asyncio
import os
import re
import sys
from pathlib import Path
from typing import Callable

import psycopg

from scribe_ingest.embedding import Embedder, FakeEmbedder, GeminiEmbedder
from scribe_ingest.ocr import FakeOcrClient, GeminiOcrClient, OcrClient
from scribe_ingest.indexer import IngestResult, build_generation, load_index_profile, register_version

EVAL_OWNER = "eval-golden-v1"  # owner of the default dataset's workspace; == eval_owner("benchmarks/datasets/golden-v1")
DEFAULT_DATASET = "benchmarks/datasets/golden-v1"
DEFAULT_CORPUS = "fixtures/corpus"
MIMES = {
    ".pdf": "application/pdf", ".md": "text/markdown", ".txt": "text/plain", ".csv": "text/csv",
    ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}
SKIP = {"FACTS.md"}
DEFAULT_CACHE = "benchmarks/cache/py-embeddings.sqlite"
Loader = Callable[[str], bytes]


class CliError(Exception):
    pass


def dataset_name(dataset: str | Path) -> str:
    return Path(dataset).resolve().name


def eval_owner(dataset: str | Path) -> str:
    """Deterministic eval-workspace owner id for a dataset directory (or bare dataset name): ``eval-<name>``."""
    name = dataset_name(dataset)
    safe = "".join(ch if (ch.isalnum() or ch in "._-") else "-" for ch in name.lower()).strip("-")
    if not safe:
        raise CliError(f"cannot derive an eval workspace id from dataset {dataset!r}")
    return f"eval-{safe}"


def load_manifest(path: str | Path, corpus: Path) -> dict[str, str]:
    """{doc name (<id>.pdf, as cases reference it) -> ingest file path under the corpus}. Refuses missing files."""
    import json

    try:
        docs = json.loads(Path(path).read_text(encoding="utf-8"))["documents"]
        mapping = {f"{d['id']}.pdf": d.get("ingest_file") or f"{d['id']}.pdf" for d in docs}
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise CliError(f"unreadable manifest {path}: {exc!r}") from None
    missing = sorted(f for f in mapping.values() if not (corpus / f).is_file())
    if missing:
        raise CliError(f"manifest {path} names ingest files missing from {corpus}: {', '.join(missing[:10])}"
                       + (f" (+{len(missing) - 10} more)" if len(missing) > 10 else ""))
    return dict(sorted(mapping.items()))


_PAGE_RE = re.compile(rb"/Type\s*/Page(?![s\w])")
EMBED_OVERHEAD = 1.25  # children + parent/overlap text embedded per document token (estimate)
PDF_TEXT_TOKENS_PER_BYTE = 1 / 12  # a text PDF's extractable text is a fraction of its bytes (estimate)
OCR_PAGE_TOKENS = (258, 700)  # (input, output) per OCR'd page: Gemini counts a PDF/image page as 258 tokens (estimate)
OCR_FRACTION_RASTER, OCR_FRACTION_OTHER_PDF = 1.0, 0.10  # image-only copies are fully OCR'd; other PDFs: allowance


def estimate_ingest_usd(files: dict[str, Path], embed_model: str | None = None, ocr_model: str | None = None) -> float:
    """Worst-case-ish pre-run estimate for ingesting {doc name: file}. Pure arithmetic over file sizes; it ignores the
    embedding cache (so a re-run is estimated as if it were cold)."""
    from scribe_ingest.embedding import DEFAULT_MODEL
    from scribe_ingest.ocr import OCR_MODEL

    from .cost import tokens_usd

    embed_tokens = 0.0
    ocr_pages = 0.0
    for name, path in files.items():
        size = path.stat().st_size
        if path.suffix.lower() == ".pdf":
            embed_tokens += size * PDF_TEXT_TOKENS_PER_BYTE
            pages = len(_PAGE_RE.findall(path.read_bytes())) or max(1, size // 50_000)
            ocr_pages += pages * (OCR_FRACTION_RASTER if ".raster." in path.name else OCR_FRACTION_OTHER_PDF)
        else:
            embed_tokens += size / 4
    usd = tokens_usd(embed_model or DEFAULT_MODEL, int(embed_tokens * EMBED_OVERHEAD))
    usd += tokens_usd(ocr_model or OCR_MODEL, int(ocr_pages * OCR_PAGE_TOKENS[0]), int(ocr_pages * OCR_PAGE_TOKENS[1]))
    return usd


def list_corpus(corpus: Path) -> list[str]:
    return sorted(p.name for p in corpus.iterdir()
                  if p.suffix.lower() in MIMES and p.name not in SKIP and not p.name.endswith(".truth.txt"))


async def ensure_eval_workspace(conn: psycopg.AsyncConnection, owner: str = EVAL_OWNER) -> str:
    # Eval tooling only: discovers/creates the eval workspace by owner_user_id, which RLS cannot express without a
    # context. It must run on a privileged (owner/superuser) connection, never as scribe_app.
    cur = await conn.execute("select id, kind from workspaces where owner_user_id = %s", (owner,))
    rows = await cur.fetchall()
    for _, kind in rows:
        if kind != "eval":
            raise CliError(f"refusing: workspace owned by {owner!r} has kind {kind!r}, not 'eval'")
    if rows:
        return str(rows[0][0])
    cur = await conn.execute("insert into workspaces(kind, owner_user_id) values ('eval', %s) returning id",
                             (owner,))
    return str((await cur.fetchone())[0])


async def reset_workspace(conn: psycopg.AsyncConnection, wid: str) -> None:
    """Wipe ONLY this (eval) workspace's index and file rows."""
    async with conn.transaction():
        await conn.execute("select set_config('app.workspace_id', %s, true)", (wid,))
        for table in ("active_indexes", "chunk_embeddings_1536", "chunk_embeddings_3072", "chunk_source_spans",
                      "chunks", "document_blocks", "index_generations"):
            await conn.execute(f"delete from {table} where workspace_id = %s", (wid,))  # noqa: S608 - fixed names
        await conn.execute("update files set desired_version_id = null, active_version_id = null where workspace_id = %s", (wid,))
        await conn.execute("delete from source_versions where workspace_id = %s", (wid,))
        await conn.execute("delete from files where workspace_id = %s", (wid,))


async def ingest_corpus(
    conn: psycopg.AsyncConnection, wid: str, names: list[str], loader: Loader, embedder: Embedder,
    *, reset: bool = False, ocr: OcrClient | None = None, owner: str = EVAL_OWNER,
) -> list[tuple[str, IngestResult]]:
    async with conn.transaction():
        await conn.execute("select set_config('app.workspace_id', %s, true)", (wid,))
        kind = (await (await conn.execute("select kind from workspaces where id = %s", (wid,))).fetchone() or [None])[0]
    if kind != "eval":
        raise CliError(f"refusing: workspace {wid} is kind {kind!r}, not 'eval'")
    if reset:
        await reset_workspace(conn, wid)
    profile = await load_index_profile(conn)
    out: list[tuple[str, IngestResult]] = []
    for name in names:
        data = loader(name)
        mime = MIMES[Path(name).suffix.lower()]
        cur = await conn.execute("select id from files where workspace_id = %s and name = %s", (wid, name))
        row = await cur.fetchone()
        if row:
            fid = row[0]
        else:
            cur = await conn.execute(
                "insert into files(name, type, size, user_id, workspace_id, storage_key, status) "
                "values (%s,%s,%s,%s,%s,%s,'processing') returning id",
                (name, mime, len(data), owner, wid, f"eval/{name}"))
            fid = (await cur.fetchone())[0]
        ver = await register_version(conn, wid, fid, data, mime, created_by=owner, storage_key=f"eval/{name}")
        out.append((name, await build_generation(conn, wid, fid, ver, data, mime, embedder, name=name, profile=profile,
                                                 ocr=ocr)))
    return out


def evaluate(results: list[tuple[str, IngestResult]]) -> list[str]:
    problems = []
    for name, r in results:
        if r.status != "ACTIVE" or r.embedded != r.expected or r.expected == 0:
            problems.append(f"{name}: status={r.status} embedded={r.embedded}/{r.expected} error={r.error_code}")
    return problems


def format_table(results: list[tuple[str, IngestResult]]) -> str:
    head = f"{'document':<40}{'blocks':>7}{'parents':>8}{'children':>9}{'emb/exp':>10}  {'status':<10}{'warnings':>9}  error"
    lines = [head, "-" * len(head)]
    for name, r in results:
        err = f"{r.error_code}: {r.message}" if r.error_code else ""
        lines.append(f"{name:<40}{r.blocks:>7}{r.parents:>8}{r.children:>9}{f'{r.embedded}/{r.expected}':>10}  "
                     f"{r.status:<10}{len(r.warnings):>9}  {err}")
    return "\n".join(lines)


def run(args) -> int:
    from . import cost as costmod

    if not args.database_url:
        print("ERROR: --database-url is required (the environment is never consulted, to avoid "
              "indexing into production).", file=sys.stderr)
        return 2
    corpus = Path(args.corpus)
    if not corpus.is_dir():
        print(f"ERROR: corpus directory not found: {corpus}", file=sys.stderr)
        return 2
    dataset = getattr(args, "dataset", None) or DEFAULT_DATASET
    manifest = getattr(args, "manifest", None)
    ledger = getattr(args, "ledger", None)
    try:
        owner = eval_owner(dataset)
        if manifest:
            mapping = load_manifest(manifest, corpus)
            files = {name: corpus / f for name, f in mapping.items()}
        else:
            files = {name: corpus / name for name in list_corpus(corpus)}
        if args.embedder != "fake":
            estimate = estimate_ingest_usd(files)
            costmod.preflight(estimate, spend_cap=getattr(args, "spend_cap", None), path=ledger,
                              what=f"ingest {len(files)} document(s) from {corpus}")
    except (CliError, costmod.SpendError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    cache = None
    metered: costmod.MeteredEmbedder | None = None
    metered_ocr: costmod.MeteredOcr | None = None
    if args.embedder == "fake":
        embedder: Embedder = FakeEmbedder()
        ocr: OcrClient = FakeOcrClient(default="[FAKE OCR - NOT REAL TEXT] placeholder transcription of a scanned page.")
        print("WARNING: FAKE embeddings (hash vectors, no semantic meaning). Use --reset before a real "
              "(gemini) run, otherwise ACTIVE fake generations are kept as they are.", file=sys.stderr)
    else:
        from .cache import DiskCache
        from .embed_cache import DiskEmbeddingCache

        cache = DiskCache(args.cache_path)
        metered = costmod.MeteredEmbedder(GeminiEmbedder(cache=DiskEmbeddingCache(cache)))
        embedder = metered  # type: ignore[assignment]
        metered_ocr = costmod.MeteredOcr(GeminiOcrClient())  # key from GOOGLE_GENERATIVE_AI_API_KEY; scanned pages are NOT cached on disk
        ocr = metered_ocr  # type: ignore[assignment]

    async def go() -> int:
        async with await psycopg.AsyncConnection.connect(args.database_url, autocommit=True,
                                                         prepare_threshold=None) as conn:
            wid = await ensure_eval_workspace(conn, owner)
            results = await ingest_corpus(conn, wid, list(files), lambda n: files[n].read_bytes(),
                                          embedder, reset=args.reset, ocr=ocr, owner=owner)
        print(f"workspace {wid} (kind eval, owner {owner}), dataset {dataset_name(dataset)}, profile {args.profile}, "
              f"embedder {'FAKE' if embedder.is_fake else embedder.model}")  # type: ignore[attr-defined]
        print(format_table(results))
        total = sum(r.expected for _, r in results)
        print(f"\nchunks to embed: {total}; embedding requests this run: {getattr(embedder, 'requests_made', 0)}"
              + (f"; cache {cache.stats}" if cache else ""))
        problems = evaluate(results)
        for p in problems:
            print(f"PROBLEM: {p}", file=sys.stderr)
        return 1 if problems else 0

    def record_spend() -> None:
        if metered is None or (metered.texts == 0 and not (metered_ocr and metered_ocr.pages)):
            return  # no provider was reached
        import uuid

        spend = costmod.RunSpend("ingest-corpus", str(uuid.uuid4()))
        spend.add(metered.usage(), calls=max(1, metered.texts))
        if metered_ocr is not None:
            spend.add(metered_ocr.usage(), calls=metered_ocr.pages)
        rec = spend.write(ledger)
        print(f"spend ledger: +${rec['usd']:.4f} (estimated={rec['estimated']}, cached={rec['cached']}); "
              f"total ${costmod.spend_total(ledger):.4f}")

    try:
        return asyncio.run(go())
    except CliError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    finally:
        record_spend()  # whatever was spent before a failure is still spend
